// Returns a horse with description + achievements localized to the given
// language, falling back to the canonical Spanish text when no translation
// exists (e.g. for 'es' or any missing entry).
export function localizeHorse(horse, language) {
  if (!horse) return horse;
  const tr = horseTranslations[language]?.[horse.id];
  if (!tr) return horse;
  return {
    ...horse,
    description: tr.description ?? horse.description,
    achievements: tr.achievements ?? horse.achievements,
  };
}
